import { expect, test } from 'bun:test';
import { and, eq } from 'drizzle-orm';
import { db } from '../src/db/client.js';
import { sourceRevisions, recordVersions } from '../src/db/schema/index.js';
import { withWorkspaceFixture } from './support/workspace-fixture.js';
const integrationTest = process.env.RUN_INTEGRATION === '1' ? test : test.skip;

integrationTest('Source revisions stay immutable while Record versions retain explicit source pins and context', async () => {
  await withWorkspaceFixture(async ({ request, headers }) => {
    const post = (path, body) => request(path, { method: 'POST', headers, body: JSON.stringify(body) });
    const patch = (path, body) => request(path, { method: 'PATCH', headers, body: JSON.stringify(body) });
    const s = await post('/api/v1/sources', { source_type: 'website', title: 'Source v1', url: 'https://example.com/v1', metadata: { edition: 1 } });
    expect(s.response.status).toBe(201);
    const sourceId = s.body.data.id;
    expect(s.body.data.revision).toBe(1);
    const r = await post('/api/v1/records', { record_type: 'plain_text', title: 'Original title', source_id: sourceId, language_code: 'ja', metadata: { context: '日本語' }, content: { text: 'Original evidence' } });
    expect(r.response.status).toBe(201);
    const recordId = r.body.data.id;
    const v1 = r.body.data.current_version;
    expect(v1.source_revision).toBe(1);
    expect(v1.source_pin_state).toBe('pinned');
    expect(v1.context_snapshot.title).toBe('Original title');
    const changed = await patch(`/api/v1/sources/${sourceId}`, { expected_revision: 1, title: 'Source v2', url: 'https://example.com/v2', metadata: { edition: 2 } });
    expect(changed.response.status).toBe(200);
    expect(changed.body.data.revision).toBe(2);
    const unchanged = await patch(`/api/v1/sources/${sourceId}`, { expected_revision: 2, title: 'Source v2' });
    expect(unchanged.response.status).toBe(200);
    expect(unchanged.body.data.revision).toBe(2);
    expect((await patch(`/api/v1/sources/${sourceId}`, { expected_revision: 1, title: 'Lost update' })).response.status).toBe(409);
    const v2 = await patch(`/api/v1/records/${recordId}`, { expected_version: 1, title: 'New title', language_code: 'en', metadata: { context: 'English' } });
    expect(v2.response.status).toBe(200);
    expect(v2.body.data.current_version.source_revision).toBe(1);
    expect(v2.body.data.current_version.context_snapshot.title).toBe('New title');
    const v3 = await patch(`/api/v1/records/${recordId}`, { expected_version: 2, source_id: sourceId });
    expect(v3.response.status).toBe(200);
    expect(v3.body.data.current_version.source_revision).toBe(2);
    const history = await request(`/api/v1/records/${recordId}/versions`, { headers });
    expect(history.body.data.map((v) => v.source_revision)).toEqual([2, 1, 1]);
    expect(history.body.data.at(-1).context_snapshot).toMatchObject({ title: 'Original title', language_code: 'ja', metadata: { context: '日本語' } });
    const old = await request(`/api/v1/sources/${sourceId}/revisions/1`, { headers });
    expect(old.body.data.snapshot).toMatchObject({ title: 'Source v1', url: 'https://example.com/v1', metadata: { edition: 1 } });
    await expect(db.update(sourceRevisions).set({ snapshot: {} }).where(eq(sourceRevisions.sourceId,sourceId)).execute()).rejects.toThrow();
    await expect(db.update(recordVersions).set({ sourceRevision: 2 }).where(eq(recordVersions.id,v1.id)).execute()).rejects.toThrow();
    const competing = await Promise.all(['A','B'].map((title) => patch(`/api/v1/sources/${sourceId}`, { expected_revision: 2, title })));
    expect(competing.map((result) => result.response.status).sort()).toEqual([200,409]);
    await expect(db.delete(sourceRevisions).where(and(eq(sourceRevisions.sourceId,sourceId),eq(sourceRevisions.revision,3))).execute()).rejects.toThrow();
    const deleted = await request(`/api/v1/sources/${sourceId}`, { method: 'DELETE', headers });
    expect(deleted.body.data.revision).toBe(4);
    const revisions = await request(`/api/v1/sources/${sourceId}/revisions?limit=2`, { headers });
    expect(revisions.body.data.map((v) => v.revision)).toEqual([4,3]);
    expect((await request(`/api/v1/sources/${sourceId}/revisions/1`, { headers })).response.status).toBe(200);
    const detached = await patch(`/api/v1/records/${recordId}`, { expected_version: 3, source_id: null });
    expect(detached.response.status).toBe(200);
    expect(detached.body.data.current_version.source_pin_state).toBe('none');
    expect(detached.body.data.current_version.source_revision).toBeNull();
    expect((await request(`/api/v1/sources/${sourceId}/revisions/1`)).response.status).toBe(401);
  });
}, 30000);
